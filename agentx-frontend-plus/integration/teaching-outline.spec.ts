import { expect, test } from "@playwright/test"

// 实际HTTP→应用→模型注册表/产物修订→PG；只在外部模型响应处替身。
// UserContext由隔离harness注入，不能据此声称验证JWT或真实教材/真实模型质量。
test("参数确认后生成大纲，修改和确认可刷新重读，外部使用者看不到材料", async ({ page, browser }) => {
  // 现有开发配置固定8088；只改实际请求目的端口，不替换HTTP响应。
  await page.context().route("http://127.0.0.1:8088/api/**", route => route.continue({ url: route.request().url().replace(":8088/", ":8089/") }))
  const owner = process.env.OUTLINE_OWNER_TOKEN!
  const other = process.env.OUTLINE_OTHER_TOKEN!
  expect(owner).toBeTruthy()
  expect(other).toBeTruthy()
  const errors: string[] = []
  page.on("pageerror", error => errors.push(error.message))
  page.on("console", message => { if (message.type() === "error" || message.type() === "warning") errors.push(message.text()) })
  await page.addInitScript(token => localStorage.setItem("auth_token", token), owner)
  await page.goto("/teaching/outlines?selection=selected")
  await expect(page.getByRole("heading", { name: "模块课时大纲", exact: true })).toBeVisible()
  await expect(page.getByLabel("每课时分钟数")).toHaveValue("45")
  await expect(page.getByLabel("学生基础")).toHaveValue("中等")
  await expect(page.getByRole("button", { name: "生成模块大纲", exact: true })).toBeDisabled()
  await page.getByLabel("生成模型", { exact: true }).selectOption("model1")
  await page.getByLabel("教材版本与版次").fill("版本待核对")
  await page.getByLabel("模块总课时").fill("1")
  await page.getByRole("checkbox").check()
  await page.getByRole("button", { name: "生成模块大纲", exact: true }).click()
  const result = page.getByRole("region", { name: "大纲结果" })
  await expect(result).toContainText("尚未确认，不能作为逐课生成依据")
  await expect(page.getByLabel("课时主题", { exact: true })).toHaveValue("导数的概念与几何意义")
  await page.getByLabel("课时主题", { exact: true }).fill("变化率与切线")
  await expect(page.getByRole("button", { name: "确认当前大纲", exact: true })).toBeDisabled()
  await page.getByRole("button", { name: "保存大纲修改", exact: true }).click()
  await expect(page.getByRole("status").filter({ hasText: "修改已保存为新修订" })).toBeVisible()
  await page.getByRole("button", { name: "确认当前大纲", exact: true }).click()
  await expect(result).toContainText("当前修订已确认")
  const saved = page.url()
  await page.reload()
  await expect(page.getByLabel("课时主题", { exact: true })).toHaveValue("变化率与切线")
  await expect(result).toContainText("当前修订已确认")
  await page.setViewportSize({ width: 375, height: 812 })
  await page.evaluate(() => window.scrollTo(0, 0))
  const overflow = await page.evaluate(() => ({ width: window.innerWidth, scroll: document.documentElement.scrollWidth, elements: Array.from(document.querySelectorAll("body *")).filter(element => element.getBoundingClientRect().right > window.innerWidth + 1).slice(-15).map(element => ({ tag: element.tagName, classes: element.className, right: element.getBoundingClientRect().right })) }))
  expect(overflow.scroll, JSON.stringify(overflow)).toBeLessThanOrEqual(overflow.width)
  await page.screenshot({ path: "/tmp/issue28-outline-mobile.png", fullPage: true })
  await page.getByRole("button", { name: "打开导航菜单" }).click()
  await expect(page.getByRole("dialog").getByRole("link", { name: "教学准备", exact: true })).toBeVisible()
  await page.getByRole("dialog").getByRole("button", { name: "Close", exact: true }).click()
  await page.setViewportSize({ width: 1365, height: 1000 })
  await page.screenshot({ path: "/tmp/issue28-outline-desktop.png", fullPage: true })
  const intruder = await browser.newContext()
  await intruder.route("http://127.0.0.1:8088/api/**", route => route.continue({ url: route.request().url().replace(":8088/", ":8089/") }))
  await intruder.addInitScript(token => localStorage.setItem("auth_token", token), other)
  const unauthorized = await intruder.newPage()
  await unauthorized.goto(saved)
  await expect(unauthorized.getByRole("alert").filter({ hasText: "大纲不存在或无访问权限" })).toBeVisible()
  await expect(unauthorized.getByRole("region", { name: "大纲结果" })).toHaveCount(0)
  await intruder.close()
  expect(errors).toEqual([])
})

import { expect, test, type APIRequestContext } from "@playwright/test"

const api = process.env.LESSON_API || "http://127.0.0.1:58088/api"
async function call(request: APIRequestContext, path: string, token: string, body?: unknown) {
  const response = body === undefined ? await request.get(`${api}${path}`, { headers: { Authorization: `Bearer ${token}` } })
    : await request.post(`${api}${path}`, { headers: { Authorization: `Bearer ${token}` }, data: body })
  const result = await response.json()
  expect(result.code, `${path}: ${result.message}`).toBe(200)
  return result.data
}


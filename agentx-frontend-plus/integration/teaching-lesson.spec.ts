  await expect(page.getByRole("region", { name: "大纲结果", exact: true })).toContainText("当前修订已确认")
  await page.getByRole("link", { name: "选择课时生成讲义与教案", exact: true }).click()
  await expect(page.getByRole("heading", { name: "课时讲义与教案", exact: true })).toBeVisible()
  await page.getByLabel("生成模型", { exact: true }).selectOption(model.id)
  await page.getByRole("button", { name: "生成课时双稿", exact: true }).click()
  const result = page.getByRole("region", { name: "课时材料结果", exact: true })
